/** 替换模板中的全部 {name} 占位符；未提供的占位符保留原样 */
export const fillPrompt = (template: string, vars: Record<string, string>) =>
  template.replace(/\{(\w+)\}/g, (m, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? vars[name] : m
  );

/** 「自动」源语言在提示词中的写法 */
export const sourceLangText = (from: string) =>
  !from || from === "auto" || from === "Automatic" ? "自动识别" : from;
